const esc = (value) =>
  String(value ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

const num = (value) => {
  const n = Number(String(value ?? "").replace(/[,\s\u20b9]/g, ""));
  return Number.isFinite(n) ? n : 0;
};

const group = (digits) => {
  let out = digits.slice(-3);
  const rest = digits.slice(0, -3);
  if (rest) out = rest.replace(/\B(?=(\d{2})+(?!\d))/g, ",") + "," + out;
  return out;
};

const money = (value, decimals = 0) => {
  const n = num(value);
  const text = Math.abs(n).toFixed(decimals);
  const [whole, frac] = text.split(".");
  return (n < 0 ? "-" : "") + group(whole) + (frac ? "." + frac : "");
};

const rupees = (value) => "\u20b9 " + money(value);
const pct = (value) => money(value, num(value) % 1 ? 2 : 0) + "%";
const lines = (text) => esc(text).replace(/\r?\n/g, "<br/>");
const row = (label, value) => `<tr><td>${esc(label)}</td><td>${value}</td></tr>`;

function table(headers, rows) {
  return `<table><thead><tr>${headers.map((h) => `<th>${esc(h)}</th>`).join("")}</tr></thead><tbody>${rows
    .map((r) => `<tr>${r.map((c) => `<td>${c}</td>`).join("")}</tr>`)
    .join("")}</tbody></table>`;
}

function deed(v) {
  const partners = v.partners ?? [];
  const clauses = v.clauses ?? [];
  const capital = partners.reduce((n, p) => n + num(p.capital), 0);
  const preamble =
    `This Deed of Partnership is made at <strong>${esc(v.place || "____________")}</strong> on ` +
    `<strong>${esc(v.execution_date || "____________")}</strong> between the partners named below.`;
  const partnerRows = partners.map((p, i) => [
    esc(`${i + 1}. ${p.name || "____________"}`),
    esc(p.pan || "—"),
    rupees(p.capital),
    pct(p.share),
  ]);
  const clauseItems = clauses
    .map((c, i) => `<p><strong>${i + 1}.</strong> ${lines(c.text || "")}</p>`)
    .join("");
  const signatureRows = partners.map((p) => [
    esc(p.name || "\u2014"),
    "________________",
    "____________",
  ]);
  return `
    <h1>Deed of Partnership</h1>
    <p><em>${esc(v.firm || "Firm name")}</em></p>
    <p>${preamble}</p>
    <h2>Partners</h2>
    ${table(["Partner", "PAN", "Capital", "Share"], partnerRows)}
    <p>Total capital: <strong>${rupees(capital)}</strong>. Profit share: <strong>${pct(
      partners.reduce((n, p) => n + num(p.share), 0),
    )}</strong>.</p>
    <h2>Terms</h2>
    <p><strong>Business.</strong> ${lines(v.business || "____________")}</p>
    ${table(
      ["Term", "Agreed"],
      [
        ["Duration", esc(v.duration || "At will")],
        ["Bank", esc(v.bank || "\u2014")],
        ["Interest on capital", esc(v.interest || "\u2014")],
      ],
    )}
    <h2>Clauses</h2>
    ${clauseItems || "<p>No clauses yet.</p>"}
    <h2>Signatures</h2>
    ${table(["Partner", "Signature", "Date"], signatureRows)}
    <p><em>Draft generated by MRH Desk. Review every clause before execution.</em></p>
  `;
}

function projectionRows(v) {
  const years = Math.max(1, Math.min(10, Math.round(num(v.years) || 5)));
  const base = num(v.base_revenue);
  const growth = num(v.growth) / 100;
  const margin = num(v.ebitda_margin) / 100;
  const tax = num(v.tax_rate) / 100;
  const capex = num(v.capex_pct) / 100;
  const depreciation = num(v.depreciation_pct) / 100;
  const interest = (num(v.interest_rate) / 100) * num(v.debt);
  const wcDays = num(v.wc_days);
  const rows = [];
  let previousWc = 0;
  for (let i = 0; i < years; i++) {
    const revenue = base * Math.pow(1 + growth, i);
    const ebitda = revenue * margin;
    const dep = revenue * depreciation;
    const ebit = ebitda - dep;
    const pbt = ebit - interest;
    const taxAmount = Math.max(0, pbt) * tax;
    const pat = pbt - taxAmount;
    const capexAmount = revenue * capex;
    const wc = (revenue * wcDays) / 365;
    const cash = pat + dep - capexAmount - (wc - previousWc);
    previousWc = wc;
    rows.push({ revenue, ebitda, dep, ebit, interest, pbt, taxAmount, pat, capexAmount, wc, cash });
  }
  return rows;
}

function projection(v) {
  const rows = projectionRows(v);
  const headers = ["Line", ...rows.map((_, i) => `Year ${i + 1}`)];
  const line = (label, key, fmt) => [esc(label), ...rows.map((r) => fmt(r[key]))];
  const body = [
    line("Revenue", "revenue", rupees),
    line("EBITDA", "ebitda", rupees),
    line("Dep.", "dep", rupees),
    line("EBIT", "ebit", rupees),
    line("Interest", "interest", rupees),
    line("Profit before tax", "pbt", rupees),
    line("Tax", "taxAmount", rupees),
    line("Profit after tax", "pat", rupees),
    line("Capex", "capexAmount", rupees),
    line("Working capital", "wc", rupees),
    line("Cash flow", "cash", rupees),
  ];
  return `
    <h1>Projected Financials</h1>
    <p><strong>${esc(v.client || "Client")}</strong> &middot; first year ${esc(v.fy || "____")}</p>
    <p>Base revenue ${rupees(v.base_revenue)}; growth ${pct(v.growth)}; EBITDA margin ${pct(v.ebitda_margin)}; tax ${pct(v.tax_rate)}.</p>
    ${table(headers, body)}
    <h2>Assumptions</h2>
    ${table(
      ["Assumption", "Value"],
      [
        ["Capex % of revenue", pct(v.capex_pct)],
        ["Depreciation % of revenue", pct(v.depreciation_pct)],
        ["Working capital days", esc(v.wc_days || "0")],
        ["Interest rate", pct(v.interest_rate)],
        ["Opening debt", rupees(v.debt)],
      ],
    )}
    <p><em>Working projection. Check the assumptions, tax treatment and opening balances before use.</em></p>
  `;
}

function provisionNumbers(v) {
  const book = num(v.book_profit);
  const taxable = book + num(v.disallowed) + num(v.dep_book) - num(v.dep_tax);
  const rate = num(v.tax_rate) / 100;
  const surcharge = num(v.surcharge) / 100;
  const cess = num(v.cess) / 100;
  const normal = taxable * rate * (1 + surcharge) * (1 + cess);
  const mat = book * 0.15 * (1 + surcharge) * (1 + cess);
  const tax = Math.max(normal, mat);
  const credits = num(v.mat_credit) + num(v.advance_tax) + num(v.tds);
  return { book, taxable, normal, mat, tax, credits, payable: tax - credits };
}

function provision(v) {
  const n = provisionNumbers(v);
  return `
    <h1>Tax Provision Working</h1>
    <p><strong>${esc(v.entity || "Entity")}</strong> &middot; FY ${esc(v.fy || "____")}</p>
    <h2>Computation</h2>
    ${table(
      ["Particulars", "Amount"],
      [
        ["Book profit", rupees(n.book)],
        ["Add: disallowed expenses", rupees(v.disallowed)],
        ["Add: depreciation (books)", rupees(v.dep_book)],
        ["Less: depreciation (income tax)", rupees(v.dep_tax)],
        ["Taxable income", `<strong>${rupees(n.taxable)}</strong>`],
        ["Normal tax (incl. surcharge and cess)", rupees(n.normal)],
        ["MAT (15% of book profit)", rupees(n.mat)],
        ["Tax payable (higher of the two)", `<strong>${rupees(n.tax)}</strong>`],
        ["Less: MAT credit, advance tax and TDS", rupees(n.credits)],
        ["Net payable / (refund)", `<strong>${rupees(n.payable)}</strong>`],
      ],
    )}
    <p><em>Working sheet only. Apply the entity's actual tax regime, surcharge thresholds and credits, and have the computation reviewed.</em></p>
  `;
}

export function previewHtml(mode, values) {
  if (mode === "projection") return projection(values);
  if (mode === "provision") return provision(values);
  return deed(values);
}

export function summaryRows(mode, v) {
  if (mode === "projection") {
    return [
      ["Client", v.client || "—"],
      ["First year", v.fy || "—"],
      ["Years", String(v.years || "5")],
      ["Base revenue", rupees(v.base_revenue)],
      ["Growth", pct(v.growth)],
      ["EBITDA margin", pct(v.ebitda_margin)],
    ];
  }
  if (mode === "provision") {
    const n = provisionNumbers(v);
    return [
      ["Entity", v.entity || "—"],
      ["Financial year", v.fy || "—"],
      ["Book profit", rupees(n.book)],
      ["Taxable income", rupees(n.taxable)],
      ["Tax payable", rupees(n.tax)],
      ["Net payable", rupees(n.payable)],
    ];
  }
  const partners = v.partners ?? [];
  return [
    ["Firm", v.firm || "—"],
    ["Place", v.place || "—"],
    ["Date", v.execution_date || "—"],
    ["Partners", String(partners.length)],
    ["Total capital", rupees(partners.reduce((n, p) => n + num(p.capital), 0))],
    ["Profit share", pct(partners.reduce((n, p) => n + num(p.share), 0))],
    ["Clauses", String((v.clauses ?? []).length)],
  ];
}

